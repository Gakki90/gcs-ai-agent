from __future__ import annotations

from datetime import datetime


SUPPORTED_PLATFORMS = ("淘宝", "京东", "拼多多", "得物")
UNSUPPORTED_MESSAGE = "暂不支持该平台，目前仅支持淘宝、京东、拼多多、得物。"


def detect_platform(task: str) -> str | None:
    normalized = task.lower()
    if "淘宝" in task or "天猫" in task:
        return "淘宝"
    if "京东" in task or "jd" in normalized:
        return "京东"
    if "拼多多" in task or "pdd" in normalized:
        return "拼多多"
    if "得物" in task:
        return "得物"
    return None


def build_user_task_prompt(task: str, platform: str) -> str:
    return (
        f"用户任务：\n{task}\n\n"
        f"目标平台：\n{platform}\n\n"
        "执行要求：\n"
        f"1. 只在{platform}内完成任务。\n"
        f"2. 如果当前app不是{platform}，先执行 Launch。\n"
        "3. 如果用户只要求搜索或浏览，不要下单、不要支付、不要提交订单。\n"
    )


